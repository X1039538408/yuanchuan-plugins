"""Regenerate embedded search data from the pinned, local pypinyin wheel.

Usage: python native/src/data/generate_search_data.py path/to/pypinyin-0.55.0-py2.py3-none-any.whl
Normal builds and installed plug-ins need neither Python nor a network connection.
"""

import hashlib
import json
from pathlib import Path
import sys
import unicodedata
import zipfile

WHEEL_SHA256 = "d53b1e8ad2cdb815fb2cb604ed3123372f5a28c6f447571244aca36fc62a286f"
DATA_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = DATA_DIR.parents[2]


def ascii_pinyin(value):
    result = ""
    for ch in unicodedata.normalize("NFD", value.lower()):
        if ch == "\u0308" and result.endswith("u"):
            result = result[:-1] + "v"
        elif "a" <= ch <= "z":
            result += ch
    return result


def cpp_string(value, prefix=""):
    return prefix + json.dumps(value, ensure_ascii=True)


def u32_string(value):
    escaped = "".join(
        "\\u%04X" % ord(ch) if ord(ch) <= 0xFFFF else "\\U%08X" % ord(ch)
        for ch in value
    )
    return 'U"' + escaped + '"'


class StringBlocks:
    """Packed offsets keep MSVC below its COFF section and string-size limits."""

    def __init__(self, limit):
        self.limit = limit
        self.blocks = [[]]
        self.length = 0
        self.offsets = {}

    def add(self, value):
        if value in self.offsets:
            return self.offsets[value]
        if self.length + len(value) + 1 > self.limit:
            self.blocks.append([])
            self.length = 0
        offset = ((len(self.blocks) - 1) << 16) | self.length
        self.blocks[-1].append(value)
        self.length += len(value) + 1
        self.offsets[value] = offset
        return offset

    def render(self, name, wide=False):
        literal = u32_string if wide else cpp_string
        kind = "char32_t" if wide else "char"
        lines = ["inline constexpr const %s* %s[] = {" % (kind, name)]
        for block in self.blocks:
            for value in block:
                lines.append("    " + literal(value)[:-1] + '\\0"')
            lines[-1] += ","
        lines += ["};"]
        return lines


def generate_pinyin(wheel):
    if hashlib.sha256(wheel.read_bytes()).hexdigest() != WHEEL_SHA256:
        raise SystemExit("Unexpected pypinyin wheel; use the pinned 0.55.0 release.")
    with zipfile.ZipFile(wheel) as archive:
        chars = json.loads(archive.read("pypinyin/pinyin_dict.json"))
        phrases = json.loads(archive.read("pypinyin/phrases_dict.json"))
        license_text = archive.read("pypinyin-0.55.0.dist-info/licenses/LICENSE.txt")
    (DATA_DIR / "pypinyin-LICENSE.txt").write_bytes(license_text)

    pinyin_strings = StringBlocks(16000)
    phrase_strings = StringBlocks(8000)
    character_rows = []
    phrase_rows = []
    for codepoint, value in sorted(chars.items(), key=lambda row: int(row[0])):
        full = ascii_pinyin(value.split(",")[0])
        if full:
            character_rows.append("    {0x%X, 0x%X}," % (int(codepoint), pinyin_strings.add(full)))
    for phrase, readings in sorted(phrases.items()):
        syllables = [ascii_pinyin(reading[0]) for reading in readings]
        if len(phrase) < 2 or not all(syllables) or len(phrase) != len(syllables):
            continue
        full = "".join(syllables)
        initials = "".join(part[0] for part in syllables)
        phrase_rows.append("    {0x%X, 0x%X, 0x%X}," % (
            phrase_strings.add(phrase), pinyin_strings.add(full), pinyin_strings.add(initials)))
    lines = [
        "// Generated by generate_search_data.py from pypinyin 0.55.0 (MIT).",
        "// Source wheel SHA-256: " + WHEEL_SHA256,
        "// Attribution and data licenses: README.md and *LICENSE.txt in this directory.",
        "#pragma once",
        "#include <cstdint>",
        "namespace xfx::search_data {",
    ]
    lines += pinyin_strings.render("pinyin_strings")
    lines += phrase_strings.render("phrase_strings", wide=True)
    lines += [
        "inline const char* pinyin_string(std::uint32_t offset) { return pinyin_strings[offset >> 16] + (offset & 0xFFFF); }",
        "inline const char32_t* phrase_string(std::uint32_t offset) { return phrase_strings[offset >> 16] + (offset & 0xFFFF); }",
        "struct CharacterPinyin { std::uint32_t codepoint; std::uint32_t full_offset; };",
        "inline constexpr CharacterPinyin characters[] = {",
    ]
    lines += character_rows
    lines += [
        "};",
        "struct PhrasePinyin { std::uint32_t text_offset; std::uint32_t full_offset; std::uint32_t initials_offset; };",
        "inline constexpr PhrasePinyin phrases[] = {",
    ]
    lines += phrase_rows
    lines += ["};", "inline constexpr unsigned max_phrase_length = %d;" % max(map(len, phrases)), "}", ""]
    (DATA_DIR / "pinyin_data.h").write_text("\n".join(lines), encoding="ascii")
    print("Embedded %d character readings and %d phrases in %d compact string blocks." % (
        len(character_rows), len(phrase_rows), len(pinyin_strings.blocks) + len(phrase_strings.blocks)))


def generate_translations():
    aliases = PROJECT_ROOT / "installer" / "XFXNativeConsole.aliases.tsv"
    lines = [
        "// Generated from installer/XFXNativeConsole.aliases.tsv; edit that file, then regenerate.",
        "#pragma once",
        "namespace xfx::search_data {",
        "struct EffectTranslation { const char* match_name; const char* english_name;",
        "    const wchar_t* chinese_name; const wchar_t* aliases; };",
        "inline constexpr EffectTranslation translations[] = {",
    ]
    count = 0
    for line in aliases.read_text(encoding="utf-8-sig").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = (line.split("\t") + [""] * 6)[:6]
        match_name, english_name, chinese_name, _, _, extra = fields
        if not chinese_name or not (match_name or english_name):
            raise SystemExit("Translation must have a name and a lookup key: " + line)
        lines.append("    {%s, %s, %s, %s}," % (
            cpp_string(match_name), cpp_string(english_name),
            cpp_string(chinese_name, "L"), cpp_string(extra, "L")))
        count += 1
    lines += ["};", "}", ""]
    (DATA_DIR / "effect_translations.h").write_text("\n".join(lines), encoding="ascii")
    print("Embedded %d effect translations." % count)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    generate_pinyin(Path(sys.argv[1]))
    generate_translations()
